"""MCP tools implemented in this package rather than mapped 1:1 to a TR.

REST tools are generated by reflection (:mod:`.tools`); these are the few
hand-written helpers on top (e.g. ``order_preview``). Each one names the
toolset it belongs to so ``KIWOOM_MCP_TOOLSETS`` filters it like the rest.

None of these may place an order. Order tools exist only as guarded REST
tools, so the live-order guard stays the single gate for them.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from typing import Any

from mcp import types

#: ``handler(api, arguments)`` — ``api`` is the server's AsyncKiwoomAPI (or
#: ``None`` in tests); helpers that need no network must ignore it.
Handler = Callable[[Any, dict[str, Any]], Awaitable[Any]]


@dataclass(frozen=True)
class LocalTool:
    name: str
    title: str
    description: str
    input_schema: dict[str, Any]
    annotations: types.ToolAnnotations
    toolset: str
    handler: Handler

    def to_mcp(self) -> types.Tool:
        return types.Tool(
            name=self.name,
            title=self.title,
            description=self.description,
            input_schema=self.input_schema,
            annotations=self.annotations,
        )
